# ---- the combination -------------------------------------------------------------------------------------------

def test_the_combined_graph_is_the_union_plus_the_data_header(schema, data, combined):
    from rdflib.compare import isomorphic

    assert len(combined) == len(schema) + len(data)
    assert isomorphic(combined, schema + data)  # isomorphic, not equal: blank nodes get new labels on every parse


def test_the_combined_graph_passes_shacl(validator):
    result = validator.validate_ontology()
    assert result.summary.conforms is True and result.summary.violation_count == 0


def test_the_combined_graph_only_gained_inverse_declarations_since_the_split():
    """Backward compatibility, kept honest: against the frozen pre-split graph nothing was lost or altered, and the
    only additions are the inverse properties the semantic review introduced (and their owl:inverseOf links)."""
    from rdflib.compare import graph_diff, to_isomorphic

    old = Graph().parse(ROOT / "tests" / "fixtures" / "combined_before_split.nt", format="nt")
    new = monolithic(Dataset.default().graph())
    _both, only_old, only_new = graph_diff(to_isomorphic(old), to_isomorphic(new))
    assert len(only_old) == 0, f"triples that existed before the split are gone: {list(only_old)[:3]}"
    added_properties = {"allergyForPatient", "treatmentForPatient", "testForPatient", "madeDiagnosis", "issuedPrescription",
                        "containedInPrescription", "orderedBy", "wardOfDepartment", "hasStaffMember", "supervises", "managedBy"}
    forward = {"hasAllergy", "receivesTreatment", "underwentTest", "diagnosedBy", "prescribedBy", "containsMedication",
               "orderedTest", "containsWard", "worksInDepartment", "reportsTo", "managesDepartment"}
    for s, p, o in only_new:
        assert local(s) in added_properties | forward, f"unexpected addition: {s} {p} {o}"
        if local(s) in forward:
            assert p == OWL.inverseOf and local(o) in added_properties


