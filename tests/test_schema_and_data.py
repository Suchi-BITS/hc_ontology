# ---- the schema ----------------------------------------------------------------------------------------------

def test_the_schema_parses_on_its_own(schema):
    assert len(set(schema.subjects(RDF.type, OWL.Class))) >= 56
    assert len(set(schema.subjects(RDF.type, OWL.ObjectProperty))) == 86
    assert len(set(schema.subjects(RDF.type, OWL.DatatypeProperty))) == 74
    header = next(schema.subjects(RDF.type, OWL.Ontology))
    assert str(header) == "http://example.org/healthcare-hospital.owl"


def test_the_schema_contains_no_synthetic_individuals(schema):
    """The only individuals allowed are controlled-vocabulary concepts and their schemes."""
    offenders = [(local(i), sorted(types_of(schema, i))) for i in individuals(schema) if not types_of(schema, i) & VOCAB]
    assert offenders == []


def test_the_schema_holds_exactly_the_vocabularies(schema):
    counts = {}
    for i in individuals(schema):
        for t in types_of(schema, i) & VOCAB:
            counts[t] = counts.get(t, 0) + 1
    assert counts == {"Specialty": 11, "AdministrativeGender": 4, "EncounterType": 4, "MedicationCategory": 7, "ConceptScheme": 4}


def test_no_sample_individual_appears_anywhere_in_the_schema_file(dataset, data):
    text = dataset.schema.read_text(encoding="utf-8")
    for name in sorted(local(i) for i in individuals(data)):
        assert f"hc:{name} " not in text and f"hc:{name}\n" not in text, f"{name} leaked into the schema"


def test_a_synthetic_patient_entering_the_schema_is_detected(schema):
    """The guard that stops the generator writing such a schema also catches one that already exists."""
    import sys

    sys.path.insert(0, str(ROOT / "scripts"))
    import generate_hc_ontology as gen

    assert gen.schema_problems(schema) == []
    polluted = Graph()
    polluted += schema
    zed = HC.PatientZed
    polluted.add((zed, RDF.type, HC.Patient))
    polluted.add((zed, RDF.type, OWL.NamedIndividual))
    problems = gen.schema_problems(polluted)
    assert len(problems) == 1 and "PatientZed" in problems[0] and "Patient" in problems[0]


