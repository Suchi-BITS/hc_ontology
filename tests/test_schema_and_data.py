"""The ontology SCHEMA (TBox) and the synthetic SAMPLE DATA (ABox) are separate artifacts.

    ontology/healthcare_schema.ttl   classes, properties, vocabularies          generated by scripts/generate_hc_ontology.py
    data/sample_data.ttl             patients, encounters, medications, ...     generated by scripts/generate_sample_data.py
    core/dataset.py                  their union: what SHACL, SPARQL, the reasoner and the projection consume

See docs/schema-and-sample-data.md.
"""

from __future__ import annotations

from pathlib import Path

import pytest
from rdflib import OWL, RDF, RDFS, Graph, Literal, Namespace, URIRef

from core.dataset import Dataset, DatasetError, as_dataset, monolithic
from tests.reasoning import needs_java, reason

ROOT = Path(__file__).resolve().parent.parent
HC = Namespace("http://example.org/healthcare-hospital.owl#")
VOCAB = {"Specialty", "AdministrativeGender", "EncounterType", "MedicationCategory", "ConceptScheme"}

# The projection of the combined graph. It was 4b0509a6163e477f... through the schema/data split (which changed nothing
# Neo4j receives) and changed once, deliberately, when the semantic review added 11 inverse pairs (35 inferred edges).
# If it changes again, what Neo4j would receive has changed: that must be intentional.
PROJECTION_FINGERPRINT = "83f2c99b2af1bca417d13982d8890630cc133e639f371d0f05482d7a73d4ab00"


def local(term) -> str:
    return str(term).split("#")[-1]


@pytest.fixture(scope="module")
def dataset():
    return Dataset.default()


@pytest.fixture(scope="module")
def schema(dataset):
    return Graph().parse(dataset.schema, format="turtle")


@pytest.fixture(scope="module")
def data(dataset):
    return Graph().parse(dataset.data, format="turtle")


@pytest.fixture(scope="module")
def combined(dataset):
    return dataset.graph()


def individuals(graph):
    return set(graph.subjects(RDF.type, OWL.NamedIndividual))


def types_of(graph, node):
    return {local(t) for t in graph.objects(node, RDF.type) if t != OWL.NamedIndividual}


