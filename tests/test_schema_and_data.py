def test_the_schema_generator_refuses_to_write_instances(tmp_path):
    """Defence in depth: even if instance-building code leaked into the schema module, the write is refused."""
    import subprocess
    import sys

    code = (
        "import sys; sys.path.insert(0, 'scripts'); sys.path.insert(0, '.')\n"
        "import generate_hc_ontology as g\n"
        "with g.onto:\n"
        "    g.C['Patient']('PatientZed')\n"
        f"g.generate({str(tmp_path / 'schema.ttl')!r}, validate_output=False)\n"
    )
    done = subprocess.run([sys.executable, "-c", code], capture_output=True, text=True, cwd=ROOT)
    assert done.returncode != 0 and "contains instance data" in done.stderr and "PatientZed" in done.stderr
    assert not (tmp_path / "schema.ttl").exists()
