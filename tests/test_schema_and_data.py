def test_the_sample_data_declares_no_schema(data):
    """Instances use the schema; they never define classes or properties."""
    for kind in (OWL.Class, OWL.ObjectProperty, OWL.DatatypeProperty, OWL.AnnotationProperty):
        assert not set(data.subjects(RDF.type, kind))
    assert not list(data.subject_objects(RDFS.subClassOf))
    assert not list(data.subject_objects(OWL.inverseOf))


def test_the_sample_data_parses_against_the_schema(schema, data):
    """Every type, property and referenced resource the data uses is defined by the schema or by the data itself."""
    classes = set(schema.subjects(RDF.type, OWL.Class))
    properties = (set(schema.subjects(RDF.type, OWL.ObjectProperty)) | set(schema.subjects(RDF.type, OWL.DatatypeProperty)))
    known = individuals(schema) | individuals(data)
    for s, p, o in data:
        if s == URIRef("http://example.org/healthcare-hospital-sample-data"):
            continue
        if p == RDF.type:
            assert o in classes or o == OWL.NamedIndividual, f"{local(s)} has unknown type {o}"
        else:
            assert p in properties, f"{local(s)} uses {p}, which the schema does not define"
            if isinstance(o, URIRef) and str(o).startswith(str(HC)):
                assert o in known, f"{local(s)} points at {local(o)}, which exists nowhere"


