def test_the_sample_data_contains_the_expected_individuals(data):
    by_type = {}
    for i in individuals(data):
        for t in types_of(data, i):
            by_type[t] = by_type.get(t, 0) + 1
    assert len(individuals(data)) == 94
    assert by_type["Patient"] == 5 and by_type["Doctor"] == 4 and by_type["Nurse"] == 2
    assert by_type["Encounter"] == 6 and by_type["Diagnosis"] == 5 and by_type["Medication"] == 6
    assert by_type["Prescription"] == 5 and by_type["Allergy"] == 1 and by_type["CodeConcept"] == 12
    assert by_type["Hospital"] == 1 and by_type["Department"] == 7


